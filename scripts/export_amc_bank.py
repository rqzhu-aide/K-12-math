"""Rebuild the browser AMC snapshot from this checkout's published JSON records.

Run with shared Python. No processing workspace, models, or packages are needed.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def browser_question(record):
    fields = {
        'id': 'ID', 'bank': 'Bank', 'responseType': 'ResponseType',
        'domain': 'domain', 'skill': 'skill', 'year': 'Year', 'level': 'Level',
        'batch': 'Batch', 'number': 'Number', 'area': 'Area',
        'question': 'Question', 'questionType': 'Question Type', 'choices': 'Choices',
        'choicesType': 'Choices Type', 'answer': 'Correct Answer',
        'gradingStatus': 'GradingStatus', 'gradingNote': 'GradingNote',
        'answerForm': 'Answer Form', 'rejectedAnswers': 'Rejected Answers',
        'solution': 'Solution', 'knowledgeGraph': 'KnowledgeGraph',
    }
    question = {name: record[key] for name, key in fields.items() if key in record}
    meta = record['Meta']
    if record.get('Solution') and not (
        meta.get('SolutionSource') == 'Adapted from MAA official solutions'
        and meta.get('OfficialSolution')
        and meta.get('SolutionAdaptation', {}).get('reviewStatus') == 'reviewed'
    ):
        raise ValueError(f"{record['ID']}: only reviewed official-source adaptations may be exported")
    question.update(
        solutionSource=meta.get('SolutionSource', ''),
        solutionSourceURL=meta.get('SolutionSourceURL', ''),
        sourceURL=meta.get('SourceURL', ''),
        figureSources=meta.get('FigureSources', {}),
        editorialNote=meta.get('EditorialNote', '') or record.get('Source Content Note', ''),
    )
    if meta.get('OfficialSolution'):
        question['officialSolution'] = meta['OfficialSolution']
    return question


def main():
    bank = ROOT / 'amc-bank'
    records = [json.loads(path.read_text(encoding='utf-8'))
               for path in sorted((bank / 'questions').glob('*.json'))]
    if not records:
        raise SystemExit('No published AMC question records were found.')
    payload = {
        'id': 'amc', 'label': 'AMC contests',
        'figuresBase': '../amc-bank/figures/',
        'attribution': 'American Mathematics Competitions, Mathematical Association of America (MAA)',
        'license': 'CC-BY-NC-SA-4.0',
        'sourceURL': 'https://maa.org/student-programs/amc/',
        'questions': [browser_question(record) for record in records],
    }
    data = ('/* AMC material: Mathematical Association of America. CC BY-NC-SA 4.0.\n'
            ' * See amc-bank/NOTICE.md for sources and modifications.\n'
            ' * Generated by scripts/export_amc_bank.py. */\n'
            'window.AMC_BANK = ' + json.dumps(payload, ensure_ascii=False, indent=0) + ';\n')
    (bank / 'bank.js').write_text(data, encoding='utf-8', newline='\n')
    print(f'Exported {len(records):,} AMC questions.')


if __name__ == '__main__':
    main()
